package goroute

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/rvadym/gocompose/pkg/internal/fs"
	"github.com/rvadym/gocompose/pkg/internal/module"
)

const (
	routerPrefix  = "router:"
	wireDirective = "//di:wire"
	generatedMark = "// Code generated by goroute. DO NOT EDIT."
	outputFile    = "router.go"
)

// Route is one //router: directive resolved to a Container field.
type Route struct {
	Method string
	Path   string
	Field  string
	File   string
	Line   int
}

// Options configures generation. Root is the module directory to scan
// (e.g. internal/app/identity) and OutputDir the container package
// directory the router.go file is written to.
type Options struct {
	Root      string
	OutputDir string
	// HandlerImport is the import path of the package declaring the Handler
	// interface. Defaults to <module>/internal/pkg/infra.
	HandlerImport string
}

// Generator holds the filesystem dependency used throughout route generation.
type Generator struct {
	fileSystem fs.FileSystem
}

// NewGenerator creates a route generator bound to fileSystem.
func NewGenerator(fileSystem fs.FileSystem) *Generator {
	return &Generator{fileSystem: fileSystem}
}

// Scan returns the routes declared under root, sorted by path.
func Scan(root string) ([]Route, error) {
	return scan(root, fs.Default())
}

// Scan returns the routes declared under root, sorted by path.
func (g *Generator) Scan(root string) ([]Route, error) {
	return scan(root, g.fileSystem)
}

func scan(root string, fileSystem fs.FileSystem) ([]Route, error) {
	var files []string
	var walk func(string) error
	walk = func(dir string) error {
		entries, err := fileSystem.ReadDir(dir)
		if err != nil {
			return err
		}
		for _, entry := range entries {
			name := entry.Name()
			path := filepath.Join(dir, name)
			if entry.IsDir() {
				if name == "testdata" || name == "vendor" || strings.HasPrefix(name, ".") {
					continue
				}
				if err := walk(path); err != nil {
					return err
				}
				continue
			}
			if strings.HasSuffix(name, ".go") && !strings.HasSuffix(name, "_test.go") {
				files = append(files, path)
			}
		}
		return nil
	}
	if err := walk(root); err != nil {
		return nil, err
	}
	sort.Strings(files)

	fset := token.NewFileSet()
	var routes []Route
	for _, filename := range files {
		source, err := fileSystem.ReadFile(filename)
		if err != nil {
			return nil, fmt.Errorf("read %s: %w", filename, err)
		}
		file, err := parser.ParseFile(fset, filename, source, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		for _, decl := range file.Decls {
			fn, ok := decl.(*ast.FuncDecl)
			if !ok || fn.Doc == nil {
				continue
			}
			found, err := routesOf(fset, fn, filename)
			if err != nil {
				return nil, err
			}
			routes = append(routes, found...)
		}
	}

	return routes, validate(routes)
}

func routesOf(fset *token.FileSet, fn *ast.FuncDecl, filename string) ([]Route, error) {
	var patterns []string
	var lines []int
	wired := false
	for _, c := range fn.Doc.List {
		text := strings.TrimSpace(c.Text)
		// gofmt rewrites "//router:GET /x" to "// router:GET /x" because the
		// pattern is not a valid directive argument, so both forms are accepted.
		body := strings.TrimSpace(strings.TrimPrefix(text, "//"))
		switch {
		case strings.HasPrefix(text, "//") && strings.HasPrefix(body, routerPrefix):
			patterns = append(patterns, strings.TrimSpace(strings.TrimPrefix(body, routerPrefix)))
			lines = append(lines, fset.Position(c.Pos()).Line)
		case text == wireDirective || strings.HasPrefix(text, wireDirective+"@"):
			wired = true
		}
	}
	if len(patterns) == 0 {
		return nil, nil
	}

	where := fmt.Sprintf("%s:%d", filename, lines[0])
	if fn.Recv != nil {
		return nil, fmt.Errorf("%s: //router: must annotate a constructor function, not method %s", where, fn.Name.Name)
	}
	if !wired {
		return nil, fmt.Errorf("%s: %s has //router: but no //di:wire, so godi does not build it", where, fn.Name.Name)
	}

	// godi names a root node's Container field after its package directory.
	field := upperCamelFromSnake(filepath.Base(filepath.Dir(filename)))

	routes := make([]Route, 0, len(patterns))
	for i, pattern := range patterns {
		method, path, err := parsePattern(pattern)
		if err != nil {
			return nil, fmt.Errorf("%s:%d: %w", filename, lines[i], err)
		}
		routes = append(routes, Route{Method: method, Path: path, Field: field, File: filename, Line: lines[i]})
	}
	return routes, nil
}

var httpMethods = map[string]bool{
	"GET": true, "HEAD": true, "POST": true, "PUT": true,
	"PATCH": true, "DELETE": true, "OPTIONS": true,
}

// parsePattern splits "METHOD /path" and validates both parts.
func parsePattern(pattern string) (method, path string, err error) {
	fields := strings.Fields(pattern)
	if len(fields) != 2 {
		return "", "", fmt.Errorf("invalid route %q (want \"<method> /path\", e.g. \"get /index\")", pattern)
	}
	method, path = strings.ToUpper(fields[0]), fields[1]
	if !httpMethods[method] {
		return "", "", fmt.Errorf("invalid HTTP method %q in route %q (want get, head, post, put, patch, delete or options)", fields[0], pattern)
	}
	if !strings.HasPrefix(path, "/") {
		return "", "", fmt.Errorf("invalid route path %q (must start with '/')", path)
	}
	return method, path, nil
}

func (r Route) key() string { return r.Method + " " + r.Path }

func validate(routes []Route) error {
	byPattern := map[string]Route{}
	fieldFile := map[string]string{}
	for _, r := range routes {
		if prev, ok := byPattern[r.key()]; ok {
			return fmt.Errorf("%s:%d: route %q already declared at %s:%d", r.File, r.Line, r.key(), prev.File, prev.Line)
		}
		byPattern[r.key()] = r

		dir := filepath.Dir(r.File)
		if other, ok := fieldFile[r.Field]; ok && other != dir {
			return fmt.Errorf("%s:%d: packages %s and %s both map to Container field %q; rename one package directory", r.File, r.Line, other, dir, r.Field)
		}
		fieldFile[r.Field] = dir
	}
	sort.Slice(routes, func(i, j int) bool { return routes[i].key() < routes[j].key() })
	return nil
}

// Generate scans options.Root and writes router.go into options.OutputDir.
// It writes an empty GetRoutes implementation when no routes are annotated,
// so callers can use the same API for every module.
func Generate(options Options) (string, error) {
	source, outPath, err := buildSource(options, fs.Default())
	if err != nil {
		return "", err
	}
	if err := os.WriteFile(outPath, source, 0o644); err != nil {
		return "", fmt.Errorf("write %s: %w", outPath, err)
	}
	return outPath, nil
}

// Generate writes the generated routes file using the generator's filesystem for inputs.
func (g *Generator) Generate(options Options) (string, error) {
	source, outPath, err := g.Render(options)
	if err != nil {
		return "", err
	}
	if err := os.WriteFile(outPath, source, 0o644); err != nil {
		return "", fmt.Errorf("write %s: %w", outPath, err)
	}
	return outPath, nil
}

// Render returns generated route source without writing it to disk.
func (g *Generator) Render(options Options) ([]byte, string, error) {
	return buildSource(options, g.fileSystem)
}

func buildSource(options Options, fileSystem fs.FileSystem) ([]byte, string, error) {
	routes, err := scan(options.Root, fileSystem)
	if err != nil {
		return nil, "", err
	}
	outPath := filepath.Join(options.OutputDir, outputFile)

	handlerImport := options.HandlerImport
	if handlerImport == "" {
		_, modulePath, err := module.NewFinder(fileSystem).FindModule(options.Root)
		if err != nil {
			return nil, "", err
		}
		handlerImport = modulePath + "/internal/pkg/infra"
	}

	source, err := render(routes, packageName(options.OutputDir, fileSystem), handlerImport)
	if err != nil {
		return nil, "", err
	}
	return source, outPath, nil
}

func render(routes []Route, pkg, handlerImport string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(generatedMark + "\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	b.WriteString("import (\n")
	if len(routes) > 0 {
		b.WriteString("\t\"fmt\"\n\n")
	}
	fmt.Fprintf(&b, "\t%q\n)\n\n", handlerImport)
	b.WriteString("// GetRoutes maps every //router:<method> <path> annotation to its handler built by BuildContainer.\n")
	b.WriteString("func GetRoutes(c *Container) (infra.HandlersConfigs, error) {\n")
	fmt.Fprintf(&b, "\troutes := make(infra.HandlersConfigs, 0, %d)\n\n", len(routes))
	for _, r := range routes {
		fmt.Fprintf(&b, "\tif c.%s == nil {\n", r.Field)
		fmt.Fprintf(&b, "\t\treturn nil, fmt.Errorf(\"route %%s %%s: handler %s is nil\", %q, %q)\n", r.Field, r.Method, r.Path)
		b.WriteString("\t}\n")
		fmt.Fprintf(&b, "\troutes = append(routes, infra.HandlerConfig{\n\t\tPath:        %q,\n\t\tMethod:      %q,\n\t\tHandlerType: fmt.Sprintf(\"%%T\", c.%s),\n\t\tHandler:     c.%s.Handle,\n\t})\n\n", r.Path, r.Method, r.Field, r.Field)
	}
	b.WriteString("\treturn routes, nil\n}\n")

	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated source: %w", err)
	}
	return out, nil
}

func packageName(dir string, fileSystem fs.FileSystem) string {
	if files, err := fileSystem.ReadDir(dir); err == nil {
		fset := token.NewFileSet()
		for _, f := range files {
			if f.IsDir() || !strings.HasSuffix(f.Name(), ".go") {
				continue
			}
			filename := filepath.Join(dir, f.Name())
			source, err := fileSystem.ReadFile(filename)
			if err != nil {
				continue
			}
			if file, err := parser.ParseFile(fset, filename, source, parser.PackageClauseOnly); err == nil {
				return file.Name.Name
			}
		}
	}
	return filepath.Base(dir)
}

func upperCamelFromSnake(s string) string {
	var b strings.Builder
	for _, part := range strings.FieldsFunc(s, func(r rune) bool { return r == '_' || r == '-' }) {
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return b.String()
}
